
import streamlit as st
import pandas as pd
import joblib

# Load trained model
model = joblib.load(
    "student_depression_decision_tree.pkl"
)

st.title(
    "Student Depression Risk Prediction"
)

st.write(
    "Machine Learning Demonstration"
)

st.warning(
    "This application is for academic purposes only and is not a clinical diagnostic tool."
)

# User inputs

gender = st.selectbox(
    "Gender",
    ["Female", "Male"]
)

age = st.number_input(
    "Age",
    min_value=17,
    max_value=28,
    value=22
)

family_background = st.selectbox(
    "Family Background",
    [
        "Lower Middle class",
        "Middle class",
        "Rich class"
    ]
)

relationship_status = st.selectbox(
    "Relationship Status",
    [
        "Single",
        "Complicated",
        "In a Relationship"
    ]
)

marital_status = st.selectbox(
    "Marital Status",
    [
        "Unmarried",
        "Married",
        "Separated"
    ]
)

living_style = st.selectbox(
    "Living Style",
    [
        "Bachelor",
        "Family"
    ]
)

current_semester = st.number_input(
    "Current Semester",
    min_value=0,
    max_value=13,
    value=5
)

cgpa = st.number_input(
    "CGPA",
    min_value=2.25,
    max_value=4.00,
    value=3.40,
    step=0.01
)

friend_circle = st.selectbox(
    "Friend Circle",
    [
        "Yes",
        "No"
    ]
)

health_condition = st.selectbox(
    "Health Condition",
    [
        "Critical",
        "Abnormal",
        "Good",
        "Normal"
    ]
)

cost_without_study = st.number_input(
    "Cost Without Study",
    min_value=0,
    max_value=32000,
    value=10000
)

home_division = st.selectbox(
    "Home Division",
    [
        "Barisal",
        "Chittagong",
        "Dhaka",
        "Khulna",
        "Mymensingh",
        "Rajshahi",
        "Rangpur",
        "Sylhet"
    ]
)

if st.button("Predict"):

    # Create input DataFrame
    student_data = pd.DataFrame({
        "Gender": [gender],
        "Age": [age],
        "Family_background": [
            family_background
        ],
        "Relationship_status": [
            relationship_status
        ],
        "Marital_status": [
            marital_status
        ],
        "Living_style": [
            living_style
        ],
        "Current_semester": [
            current_semester
        ],
        "CGPA": [cgpa],
        "friend_circle": [
            friend_circle
        ],
        "Health_condition": [
            health_condition
        ],
        "Cost_without_study": [
            cost_without_study
        ],
        "Home_division": [
            home_division
        ]
    })

    # Make prediction
    prediction = model.predict(
        student_data
    )[0]

    probability = model.predict_proba(
        student_data
    )[0][1]

    # Display result
    if prediction == 1:

        st.warning(
            "Model Prediction: Higher Predicted Risk"
        )

    else:

        st.success(
            "Model Prediction: Lower Predicted Risk"
        )

    st.write(
        f"Predicted positive-class probability: {probability:.2%}"
    )

    st.caption(
        "This result is generated by a machine learning model for educational purposes and should not be treated as a medical diagnosis."
    )
